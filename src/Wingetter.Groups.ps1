function Get-WingetterRetryPackagesFromReport {
    param([object]$Report)

    if ($null -eq $Report -or $null -eq $Report.packages) { return @() }
    $retryStatuses = @("FAILED", "CANCELLED", "NOT RUN")
    $retryable = [System.Collections.ArrayList]::new()
    foreach ($pkg in @($Report.packages)) {
        $status = [string]$pkg.status
        if ($retryStatuses -contains $status) {
            $installOptions = $null
            if ($Report.runPlan -and $Report.runPlan.Packages) {
                foreach ($planPkg in @($Report.runPlan.Packages)) {
                    if ([string]$planPkg.PackageId -eq [string]$pkg.packageId -and $planPkg.PSObject.Properties["InstallOptions"]) {
                        $installOptions = $planPkg.InstallOptions
                        break
                    }
                }
            }
            [void]$retryable.Add([PSCustomObject]@{
                Name           = [string]$pkg.name
                WingetId       = [string]$pkg.packageId
                SourceName     = if ($pkg.source) { [string]$pkg.source } else { "winget" }
                PriorStatus    = $status
                InstallOptions = $installOptions
            })
        }
    }
    return [object[]]$retryable.ToArray()
}

function New-WingetterComplianceReport {
    param(
        [string]$ProfileName,
        [object[]]$DesiredPackages,
        [hashtable]$InstalledRecords = @{},
        [hashtable]$PinStatusesById = @{},
        [object]$SourcePolicy = $null
    )

    $results = [System.Collections.ArrayList]::new()
    $stateCount = @{ Missing = 0; Current = 0; UpdateAvailable = 0; Pinned = 0; SourceBlocked = 0; Unresolved = 0 }

    foreach ($pkg in @($DesiredPackages)) {
        $id = if ($pkg -is [string]) { $pkg }
              elseif ($pkg.PSObject.Properties["WingetId"]) { [string]$pkg.WingetId }
              elseif ($pkg.PSObject.Properties["PackageIdentifier"]) { [string]$pkg.PackageIdentifier }
              else { [string]$pkg }
        $name = if ($pkg.PSObject.Properties["Name"]) { [string]$pkg.Name } else { $id }

        $installed = if ($InstalledRecords.ContainsKey($id)) { $InstalledRecords[$id] } else { $null }
        $pin = if ($PinStatusesById.ContainsKey($id)) { $PinStatusesById[$id] } else { $null }
        $isPinned = ($null -ne $pin -and $pin.PSObject.Properties["IsPinned"] -and [bool]$pin.IsPinned)

        $sourceBlocked = $false
        if ($null -ne $SourcePolicy -and [bool]$SourcePolicy.CorporateMode -and [bool]$SourcePolicy.RequireAllowedSource) {
            $sourceName = if ($null -ne $installed) { [string]$installed.Source } elseif ($pkg.PSObject.Properties["SourceName"]) { [string]$pkg.SourceName } else { "winget" }
            $allowedNames = @($SourcePolicy.AllowedSources | ForEach-Object { [string]$_.Name })
            if ($allowedNames.Count -gt 0 -and $allowedNames -notcontains $sourceName) { $sourceBlocked = $true }
        }

        $state = "Unresolved"
        if ($sourceBlocked) {
            $state = "SourceBlocked"
        } elseif ($null -eq $installed) {
            $state = "Missing"
        } elseif ($installed.PSObject.Properties["IsUpdateAvailable"] -and [bool]$installed.IsUpdateAvailable) {
            $state = if ($isPinned) { "Pinned" } else { "UpdateAvailable" }
        } else {
            $state = "Current"
        }

        $stateCount[$state]++
        [void]$results.Add([PSCustomObject][ordered]@{
            PackageId        = $id
            Name             = $name
            State            = $state
            InstalledVersion = if ($installed) { [string]$installed.InstalledVersion } else { "" }
            AvailableVersion = if ($installed) { [string]$installed.AvailableVersion } else { "" }
            Source           = if ($installed) { [string]$installed.Source } else { "" }
            PinType          = if ($isPinned) { [string]$pin.PinType } else { "" }
            SourceBlocked    = [bool]$sourceBlocked
        })
    }

    [PSCustomObject][ordered]@{
        Schema       = "Wingetter.ComplianceReport.v1"
        GeneratedUtc = (Get-Date).ToUniversalTime().ToString("o")
        ProfileName  = $ProfileName
        TotalDesired = @($DesiredPackages).Count
        Summary      = [PSCustomObject][ordered]@{
            Current         = [int]$stateCount["Current"]
            Missing         = [int]$stateCount["Missing"]
            UpdateAvailable = [int]$stateCount["UpdateAvailable"]
            Pinned          = [int]$stateCount["Pinned"]
            SourceBlocked   = [int]$stateCount["SourceBlocked"]
            Unresolved      = [int]$stateCount["Unresolved"]
        }
        Packages     = [object[]]$results.ToArray()
    }
}

function Export-WingetterRunLockfile {
    param(
        [object]$Report,
        [string]$FilePath
    )

    if ($null -eq $Report -or $null -eq $Report.packages) { return $null }
    $entries = [System.Collections.ArrayList]::new()
    foreach ($pkg in @($Report.packages)) {
        $status = [string]$pkg.status
        if ($status -ne "SUCCESS" -and $status -ne "UP TO DATE") { continue }

        $installerUrl = ""
        $installerHash = ""
        if (![string]::IsNullOrWhiteSpace([string]$pkg.resultPath) -and (Test-Path -LiteralPath ([string]$pkg.resultPath))) {
            try {
                $resultData = Get-Content -LiteralPath ([string]$pkg.resultPath) -Raw | ConvertFrom-Json
                if ($resultData.PSObject.Properties["Command"]) {
                    $cmd = [string]$resultData.Command
                    if ($cmd -match '--version\s+"?([^\s"]+)') { }
                }
            } catch {}
        }

        $installOptions = $null
        if ($Report.runPlan -and $Report.runPlan.Packages) {
            foreach ($planPkg in @($Report.runPlan.Packages)) {
                if ([string]$planPkg.PackageId -eq [string]$pkg.packageId -and $planPkg.PSObject.Properties["InstallOptions"]) {
                    $installOptions = $planPkg.InstallOptions
                    break
                }
            }
        }

        [void]$entries.Add([PSCustomObject][ordered]@{
            PackageId        = [string]$pkg.packageId
            Name             = [string]$pkg.name
            Source           = if ($pkg.source) { [string]$pkg.source } else { "winget" }
            InstalledVersion = [string]$pkg.installedVersion
            AvailableVersion = [string]$pkg.availableVersion
            Status           = $status
            InstallOptions   = $installOptions
        })
    }

    $lockfile = [PSCustomObject][ordered]@{
        Schema       = "Wingetter.Lockfile.v1"
        GeneratedUtc = (Get-Date).ToUniversalTime().ToString("o")
        ProfileName  = if ($Report.profileName) { [string]$Report.profileName } else { "" }
        PackageCount = $entries.Count
        Packages     = [object[]]$entries.ToArray()
    }

    if (![string]::IsNullOrWhiteSpace($FilePath)) {
        Set-WingetterFileAtomic -Path $FilePath -Content ($lockfile | ConvertTo-Json -Depth 8) -Encoding UTF8
    }
    return $lockfile
}

function Compare-WingetterLockfile {
    param(
        [object]$Lockfile,
        [hashtable]$InstalledRecords = @{}
    )

    if ($null -eq $Lockfile -or $null -eq $Lockfile.Packages) { return @() }
    $drifts = [System.Collections.ArrayList]::new()
    foreach ($entry in @($Lockfile.Packages)) {
        $id = [string]$entry.PackageId
        $installed = if ($InstalledRecords.ContainsKey($id)) { $InstalledRecords[$id] } else { $null }
        $drift = "None"
        if ($null -eq $installed) {
            $drift = "Missing"
        } elseif ([string]$installed.InstalledVersion -ne [string]$entry.InstalledVersion) {
            $drift = "VersionChanged"
        }
        [void]$drifts.Add([PSCustomObject][ordered]@{
            PackageId       = $id
            Name            = [string]$entry.Name
            LockedVersion   = [string]$entry.InstalledVersion
            CurrentVersion  = if ($installed) { [string]$installed.InstalledVersion } else { "" }
            Drift           = $drift
        })
    }
    return [object[]]$drifts.ToArray()
}

