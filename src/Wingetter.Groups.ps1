$Script:GroupsDir = "$env:APPDATA\Wingetter"
$Script:GroupsFile = "$Script:GroupsDir\groups.json"
if (!(Test-Path $Script:GroupsDir)) { New-Item -ItemType Directory -Path $Script:GroupsDir -Force | Out-Null }

function Get-SavedGroups {
    if (Test-Path $Script:GroupsFile) {
        try { return (Get-Content $Script:GroupsFile -Raw | ConvertFrom-Json) }
        catch {
            Move-WingetterCorruptFileAside -Path $Script:GroupsFile
            return [PSCustomObject]@{}
        }
    }
    return [PSCustomObject]@{}
}

function Save-WingetterGroupsFile {
    param([hashtable]$Groups)
    $json = $Groups | ConvertTo-Json -Depth 8
    Set-WingetterFileAtomic -Path $Script:GroupsFile -Content $json -Encoding UTF8
}

function Save-GroupToFile {
    param(
        [string]$Name,
        [string[]]$PackageIds,
        [object[]]$PackageEntries = @()
    )
    $groups = Get-SavedGroups
    $ht = @{}
    foreach ($prop in $groups.PSObject.Properties) { $ht[$prop.Name] = $prop.Value }
    $entries = @(ConvertTo-WingetterGroupPackageEntries -PackageIds $PackageIds -PackageEntries $PackageEntries -AllowCustomInstallOptions)
    $hasInstallOptions = $false
    foreach ($entry in @($entries)) {
        if ($entry.PSObject.Properties["InstallOptions"] -and !(Test-WingetterInstallOptionsEmpty -InstallOptions $entry.InstallOptions)) {
            $hasInstallOptions = $true
            break
        }
    }

    if ($hasInstallOptions) {
        $ht[$Name] = [ordered]@{
            Schema     = "Wingetter.SavedGroup.v1"
            PackageIds = [string[]]@($entries | ForEach-Object { [string]$_.PackageIdentifier })
            Packages   = [object[]]$entries
        }
    } else {
        $ht[$Name] = [string[]]@($entries | ForEach-Object { [string]$_.PackageIdentifier })
    }
    Save-WingetterGroupsFile -Groups $ht
}

function Remove-GroupFromFile {
    param([string]$Name)
    $groups = Get-SavedGroups
    $ht = @{}
    foreach ($prop in $groups.PSObject.Properties) { if ($prop.Name -ne $Name) { $ht[$prop.Name] = $prop.Value } }
    Save-WingetterGroupsFile -Groups $ht
}

function ConvertTo-WingetterPowerShellSingleQuotedString {
    param([string]$Value)
    "'" + (([string]$Value) -replace "'", "''") + "'"
}

function Export-GroupAsPS1 {
    param(
        [string]$GroupName,
        [string[]]$PackageIds,
        [string]$FilePath,
        [bool]$Silent = $true,
        [bool]$AcceptAgreements = $true,
        [object[]]$PackageEntries = @()
    )
    $entries = @(ConvertTo-WingetterGroupPackageEntries -PackageIds $PackageIds -PackageEntries $PackageEntries -AllowCustomInstallOptions)
    $sb = [System.Text.StringBuilder]::new()
    [void]$sb.AppendLine("<#")
    [void]$sb.AppendLine(".SYNOPSIS")
    [void]$sb.AppendLine("    WinGet Package Group Installer - $GroupName")
    [void]$sb.AppendLine(".DESCRIPTION")
    [void]$sb.AppendLine("    Auto-generated by Wingetter")
    [void]$sb.AppendLine("    Installs $($entries.Count) packages via winget")
    [void]$sb.AppendLine("    Generated: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')")
    [void]$sb.AppendLine("#>")
    [void]$sb.AppendLine("")
